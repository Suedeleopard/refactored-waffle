/* ════════════════════════════════════════════════════════════════════════
   THE SWIPE FILE — this is the marketing.

   Every teardown here does three jobs at once: it proves the method works,
   it feeds the weekly post, and it is an unsolicited pitch to whoever runs
   that category. Adding one is the highest-leverage hour of the week.

   To add a teardown: copy the shape below and put it at the top of the
   array. Newest first. No CMS, no build step, no database.
   ════════════════════════════════════════════════════════════════════════ */

export type Teardown = {
  /** URL segment: /teardowns/<slug> */
  slug: string;
  /**
   * Who made the leap.
   *
   * "found"   — a real business already behaving this way. Not your idea. You
   *   spotted it and decoded why it works. Credibility, and proof the pattern
   *   exists in the wild rather than only in your head.
   * "made"    — your own ideas, generated by running the method. Nobody is
   *   doing this yet. This is the thinking people are buying.
   * "shipped" — you ran the method and it went live for a real client. Rarest
   *   and worth the most: it is the only kind that proves the method survives
   *   contact with a budget.
   *
   * Never blur them. Claiming someone else's positioning is the fastest way to
   * lose the authority the found ones buy you.
   */
  kind: "found" | "made" | "shipped";
  /** The real business. Required for "found" and "shipped". */
  credit?: string;
  /** The anchor. The business whose behaviour is being swapped. */
  x: string;
  /** The parallel. The industry whose behaviour is being borrowed. */
  y: string;
  /** Shown as the headline. Usually "A [x] behaving like a [y]". */
  title: string;
  /** One line for cards and previews. */
  standfirst: string;
  /** The audience both industries already share. This is the whole argument. */
  sharedAudience: string;
  /** Why this pairing is not random — the friction in X that Y already solves. */
  rationale: string;
  /** The ideas. Four to six is the right number: enough to prove it, few enough to read. */
  ideas: { name: string; body: string }[];
  /**
   * What happened. Only for "shipped" — it's the reason that kind exists, and
   * the single most persuasive thing on the page. Keep every claim defensible.
   */
  outcome?: string;
  /** Free-text date label, e.g. "March 2026". Display only. */
  published: string;
};

