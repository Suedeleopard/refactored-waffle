/** Newest first, as authored. */
export function getTeardowns(): Teardown[] {
  return teardowns;
}

/** Short label + explanation for the found/made distinction. */
export function kindLabel(t: Teardown): { label: string; note: string } {
  switch (t.kind) {
    case "found":
      return {
        label: "Found in the wild",
        note: `${t.credit ?? "This business"} is already doing this. I didn't invent it, I took it apart to show how it works.`,
      };
    case "shipped":
      return {
        label: "Built and shipped",
        note: `Work I did for ${t.credit ?? "a client"}. The method run properly, approved, and put into the world.`,
      };
    default:
      return {
        label: "My idea",
        note: "Nobody is doing this yet. It's what came out of running the method on this pairing.",
      };
  }
}

export function getTeardown(slug: string): Teardown | undefined {
  return teardowns.find((t) => t.slug === slug);
}
